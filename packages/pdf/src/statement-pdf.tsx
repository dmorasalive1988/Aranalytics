function fontsDir(): string {
  const candidates = [
    process.env.PLUMA_PDF_FONTS_DIR,
    resolve(/*turbopackIgnore: true*/ process.cwd(), 'packages/pdf/fonts'),
    resolve(/*turbopackIgnore: true*/ process.cwd(), '../../packages/pdf/fonts'),
    resolve(/*turbopackIgnore: true*/ process.cwd(), '../pdf/fonts'),
    resolve(/*turbopackIgnore: true*/ process.cwd(), 'fonts'),
  ].filter((x): x is string => !!x);
  const found = candidates.find((d) => existsSync(resolve(/*turbopackIgnore: true*/ d, 'dm-sans-latin-400-normal.woff')));
  if (!found) throw new Error('No se encontraron las fuentes del PDF (PLUMA_PDF_FONTS_DIR)');
  return found;
}

let registered = false;
function registerFonts() {
  if (registered) return;
  const dir = fontsDir();
  Font.register({
    family: 'DM Sans',
    fonts: [
      { src: resolve(/*turbopackIgnore: true*/ dir, 'dm-sans-latin-400-normal.woff'), fontWeight: 400 },
      { src: resolve(/*turbopackIgnore: true*/ dir, 'dm-sans-latin-500-normal.woff'), fontWeight: 500 },
      { src: resolve(/*turbopackIgnore: true*/ dir, 'dm-sans-latin-700-normal.woff'), fontWeight: 700 },
    ],
  });
  Font.register({ family: 'Bricolage Grotesque', src: resolve(/*turbopackIgnore: true*/ dir, 'bricolage-grotesque-latin-800-normal.woff'), fontWeight: 800 });
  Font.registerHyphenationCallback((w) => [w]);
  registered = true;
}

