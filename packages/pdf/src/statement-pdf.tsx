function StatementDoc({ v }: { v: StatementView }) {
  const t = L[v.locale];
  const money = (cents: number) => `${v.currency} ${new Intl.NumberFormat(v.intlLocale, { minimumFractionDigits: 2, maximumFractionDigits: 2 }).format(cents / 100)}`;
  const pct = (bps: number) => new Intl.NumberFormat(v.intlLocale, { style: 'percent', maximumFractionDigits: 2 }).format(bps / 10000);
  const date = (d: string) => new Intl.DateTimeFormat(v.intlLocale, { dateStyle: 'long', timeZone: 'UTC' }).format(new Date(d));
  const Table = ({ title, rows }: { title: string; rows: { key: string; netCents: number }[] }) => (
    <View wrap={false}>
      <Text style={s.h2}>{title}</Text>
      {rows.map((r) => (
        <View key={r.key} style={s.row}>
          <Text style={s.cellMain}>{r.key}</Text>
          <Text style={s.num}>{money(r.netCents)}</Text>
        </View>
      ))}
    </View>
  );
  const summary: [string, number, boolean?][] = [
    [t.opening, v.totals.openingCents],
    [t.gross, v.totals.grossCents],
    [`${t.commission} (${pct(v.plan.commissionBps)})`, 0 - v.totals.commissionCents || 0],
    [t.withholding, 0 - v.totals.withholdingCents || 0],
    [t.net, v.totals.netCents, true],
    [t.closing, v.totals.closingCents, true],
  ];
  return (
    <Document title={`Pluma · ${t.title} · ${v.periodCode}`} author="Pluma" creator="Pluma" producer="Pluma">
      <Page size="A4" style={s.page}>
        <View style={s.band}>
          <View style={{ flexDirection: 'row', alignItems: 'center', gap: 8 }}>
            <Symbol />
            <Text style={s.word}>pluma</Text>
          </View>
          <Text style={s.bandTitle}>{t.title} · {v.periodCode}</Text>
        </View>
        <View style={s.body}>
          <View style={s.meta}>
            <View style={s.metaItem}><Text style={s.label}>{t.writer}</Text><Text style={s.value}>{v.writer.artistName ? `${v.writer.artistName} · ${v.writer.legalName}` : v.writer.legalName}</Text></View>
            <View style={s.metaItem}><Text style={s.label}>{t.period}</Text><Text style={s.value}>{v.periodCode}</Text></View>
            <View style={s.metaItem}><Text style={s.label}>{t.payDate}</Text><Text style={s.value}>{date(v.payDate)}</Text></View>
            <View style={s.metaItem}><Text style={s.label}>{t.plan}</Text><Text style={s.value}>{v.plan.code === 'pro' ? 'Pro' : v.locale === 'pt-BR' ? 'Sócio' : 'Socio'} · {pct(v.plan.commissionBps)}</Text></View>
            {v.writer.ipi && <View style={s.metaItem}><Text style={s.label}>IPI</Text><Text style={s.value}>{v.writer.ipi}</Text></View>}
          </View>
          <View style={s.netBox}>
            <Text style={{ fontSize: 9, fontWeight: 500 }}>{t.net}</Text>
            <Text style={s.netAmount}>{money(v.totals.netCents)}</Text>
          </View>
          <View wrap={false}>
            <Text style={s.h2}>{t.summary}</Text>
            {summary.map(([k, val, strong]) => (
              <View key={k} style={s.row}>
                <Text style={[s.cellMain, strong ? s.bold : {}]}>{k}</Text>
                <Text style={[s.num, strong ? s.bold : {}]}>{money(val)}</Text>
              </View>
            ))}
            {v.totals.adjustmentsCents !== 0 && <View style={s.row}><Text style={s.cellMain}>{t.adjustments}</Text><Text style={s.num}>{money(v.totals.adjustmentsCents)}</Text></View>}
            {v.totals.heldCents !== 0 && <View style={s.row}><Text style={s.cellMain}>{t.held}</Text><Text style={s.num}>{money(v.totals.heldCents)}</Text></View>}
          </View>
          <View>
            <Text style={s.h2}>{t.byWork}</Text>
            <View style={[s.row, { borderBottomColor: C.tinta }]}>
              <Text style={[s.cellMain, s.label]}>{t.work}</Text><Text style={[s.num, s.label]}>{t.share}</Text><Text style={[s.num, s.label]}>{t.grossShort}</Text><Text style={[s.num, s.label]}>{t.netShort}</Text>
            </View>
            {v.byWork.map((w) => (
              <View key={w.title} style={s.row} wrap={false}>
                <Text style={s.cellMain}>{w.title}{w.held ? ` (${t.holdNote})` : ''}</Text>
                <Text style={s.num}>{pct(w.shareBps)}</Text>
                <Text style={s.num}>{money(w.grossCents)}</Text>
                <Text style={[s.num, s.bold]}>{money(w.netCents)}</Text>
              </View>
            ))}
          </View>
          <Table title={t.byType} rows={v.byIncomeType.map((r) => ({ key: (t.types as Record<string, string>)[r.key] ?? r.key, netCents: r.netCents }))} />
          <Table title={t.bySource} rows={v.bySource} />
          <Table title={t.byTerritory} rows={v.byTerritory} />
        </View>
        <View style={s.footer} fixed>
          <Text>{t.footer}</Text>
          <Text render={({ pageNumber, totalPages }) => `${v.statementId.slice(0, 8)} · ${pageNumber}/${totalPages}`} />
        </View>
      </Page>
    </Document>
  );
}

export async function renderStatementPdf(view: StatementView): Promise<Buffer> {
  registerFonts();
  return renderToBuffer(<StatementDoc v={view} />);
}
